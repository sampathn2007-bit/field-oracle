"""Prepare data"""

df_model = df.dropna(
    subset=["Date", "Crop_Yield"]
).copy()

# Investigate negative target values rather than silently accepting them.
if (df_model["Crop_Yield"] < 0).any():
    raise ValueError(
        "Negative Crop_Yield values found. Investigate them before training."
    )

# Negative wind speed is physically invalid.
# Convert it to missing so the training pipeline can impute it.
df_model.loc[
    df_model["Wind_Speed"] < 0,
    "Wind_Speed"
] = np.nan

# Extract calendar features.
df_model["Year"] = df_model["Date"].dt.year
df_model["Month"] = df_model["Date"].dt.month
df_model["DayOfYear"] = df_model["Date"].dt.dayofyear

# Cyclical features preserve the fact that December and January are adjacent.
df_model["Month_Sin"] = np.sin(
    2 * np.pi * df_model["Month"] / 12
)
df_model["Month_Cos"] = np.cos(
    2 * np.pi * df_model["Month"] / 12
)
df_model["DayOfYear_Sin"] = np.sin(
    2 * np.pi * df_model["DayOfYear"] / 365.25
)
df_model["DayOfYear_Cos"] = np.cos(
    2 * np.pi * df_model["DayOfYear"] / 365.25
)

print("Prepared dataset shape:", df_model.shape)
print("Missing wind speeds after validation:",
      df_model["Wind_Speed"].isna().sum())

display(df_model.head())

"""define input Features and Targets"""

numeric_features = [
    "Soil_pH",
    "Temperature",
    "Humidity",
    "Wind_Speed",
    "N",
    "P",
    "K",
    "Year",
    "Month_Sin",
    "Month_Cos",
    "DayOfYear_Sin",
    "DayOfYear_Cos"
]

categorical_features = [
    "Crop_Type",
    "Soil_Type"
]

feature_columns = numeric_features + categorical_features

X = df_model[feature_columns].copy()
y = df_model["Crop_Yield"].copy()

print("Input shape:", X.shape)
print("Target shape:", y.shape)
print("\nFeatures used:")
print(feature_columns)

display(X.head())

"""split the data"""

df_model = df_model.sort_values("Date").reset_index(drop=True)

unique_dates = np.sort(df_model["Date"].unique())

if len(unique_dates) < 2:
    raise ValueError("Not enough distinct dates for a chronological split.")

split_index = int(len(unique_dates) * 0.80)
split_index = min(max(split_index, 1), len(unique_dates) - 1)

cutoff_date = unique_dates[split_index]

train_df = df_model[df_model["Date"] < cutoff_date].copy()
test_df = df_model[df_model["Date"] >= cutoff_date].copy()

X_train = train_df[feature_columns]
y_train = train_df["Crop_Yield"]

X_test = test_df[feature_columns]
y_test = test_df["Crop_Yield"]

print("Cutoff date:", cutoff_date)
print("Training records:", len(X_train))
print("Testing records:", len(X_test))

print("\nTraining date range:")
print(train_df["Date"].min(), "to", train_df["Date"].max())

print("\nTesting date range:")
print(test_df["Date"].min(), "to", test_df["Date"].max())

"""Building Preprocessing Pipeline"""

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.ensemble import RandomForestRegressor

numeric_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median"))
])

categorical_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer(
    transformers=[
        ("numeric", numeric_transformer, numeric_features),
        ("categorical", categorical_transformer, categorical_features)
    ]
)

yield_model = Pipeline(steps=[
    ("preprocessor", preprocessor),
    ("regressor", RandomForestRegressor(
        n_estimators=200,
        min_samples_leaf=2,
        random_state=42,
        n_jobs=-1
    ))
])

print("Preprocessing and regression pipeline created.")

"""train The Data"""

yield_model.fit(X_train, y_train)

print("Crop yield model trained successfully.")

"""Evaluate the model"""

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

y_pred = yield_model.predict(X_test)

mae = mean_absolute_error(y_test, y_pred)
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
r2 = r2_score(y_test, y_pred)

print(f"MAE:  {mae:.4f}")
print(f"RMSE: {rmse:.4f}")
print(f"R²:   {r2:.4f}")

"""Compare with Baseline Model"""

from sklearn.dummy import DummyRegressor

baseline_model = DummyRegressor(strategy="mean")
