"""7. Define features and Targets"""

# Define features and target
feature_columns = [
    "Temperature",
    "Moisture",
    "Rainfall",
    "PH",
    "Nitrogen",
    "Phosphorous",
    "Potassium",
    "Carbon",
    "Soil",
    "Crop"
]

# Create a copy of the original dataset
df_clean = df.copy()

# Treat negative measurements as invalid/missing
invalid_columns = [
    "Rainfall",
    "Phosphorous",
    "Potassium",
    "Carbon"
]

print("Negative values detected before cleaning:")
for col in invalid_columns:
    count = (df_clean[col] < 0).sum()
    print(f"{col}: {count}")

    df_clean.loc[df_clean[col] < 0, col] = np.nan

# Create features and target from the cleaned dataset
X = df_clean[feature_columns].copy()
y = df_clean["Fertilizer"].copy()

print("\nInput shape:", X.shape)
print("Target shape:", y.shape)

print("\nMissing values after cleaning:")
print(X[invalid_columns].isnull().sum())

print("\nTarget classes:")
print(sorted(y.unique()))

"""8. Split the Data"""

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

print("\nTraining target distribution:")
print(y_train.value_counts())

"""9. Build the preprocessing pipeline"""

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import Pipeline

from sklearn.impute import SimpleImputer
from sklearn.ensemble import RandomForestClassifier

numeric_features = [
    "Temperature",
    "Moisture",
    "Rainfall",
    "PH",
    "Nitrogen",
    "Phosphorous",
    "Potassium",
    "Carbon"
]

categorical_features = [
    "Soil",
    "Crop"
]

numeric_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median"))
])

categorical_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer(
    transformers=[
        ("numeric", numeric_transformer, numeric_features),
        ("categorical", categorical_transformer, categorical_features)
    ]
)

fertilizer_model = Pipeline(steps=[
    ("preprocessor", preprocessor),
    ("classifier", RandomForestClassifier(
        n_estimators=300,
        random_state=42,
        class_weight="balanced",
        n_jobs=-1
    ))
])

print("Preprocessing and model pipeline created.")

"""Train the model"""

fertilizer_model.fit(X_train, y_train)

print("Fertilizer recommendation model trained successfully!")

"""Evaluate the Model"""

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    ConfusionMatrixDisplay
)

y_pred = fertilizer_model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)

print(f"Test accuracy: {accuracy:.4f}")
print(f"Test accuracy: {accuracy * 100:.2f}%")

print("\nClassification report:")
print(classification_report(
    y_test,
    y_pred,
    zero_division=0
))

"""Visualize The confusion matrix"""

plt.figure(figsize=(12, 10))

ConfusionMatrixDisplay.from_predictions(
    y_test,
    y_pred,
    xticks_rotation=90,
    cmap="Blues",
    colorbar=False
)

plt.title("Fertilizer Recommendation — Confusion Matrix")
plt.tight_layout()
plt.show()

